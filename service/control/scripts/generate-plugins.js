#!/usr/bin/env node
// Writes src/plugins.generated.js: a static import of the control entry of
// every enabled plugin in the plugin config, so wrangler bundles them into the
// Worker (Workers cannot load code at runtime, decision 20). wrangler.jsonc
// runs this as the build command, so `wrangler dev` and `wrangler deploy`
// always pick up the current yolo.config.json.
//
// The config is found like the node finds it: YOLO_CONFIG (also from the
// repository .env), else yolo.config.json in the repository, else
// plugins/official.json. Plugin
// options are copied into the bundle, so keep secrets out of a control
// entry's options; use Worker secrets instead.
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, relative, sep } from "node:path";
import { loadEnvFile } from "node:process";
import { fileURLToPath } from "node:url";
import { loadPluginConfig } from "@useyolo/plugin-api/host";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
export const OUTPUT = fileURLToPath(new URL("../src/plugins.generated.js", import.meta.url));

// Node and esbuild resolve an import from the importer's real path, so the
// relative path must be between real paths (macOS /var is /private/var).
function importPath(fromFile, toFile) {
  const path = relative(realpathSync(dirname(fromFile)), realpathSync(toFile)).split(sep).join("/");
  return path.startsWith(".") ? path : `./${path}`;
}

// The config path relative to the repository, or absolute when outside it.
function shown(root, path) {
  const inside = relative(root, path);
  return inside.startsWith("..") ? path : inside.split(sep).join("/");
}

export function renderPluginModule({ configPath, plugins, outFile, root = ROOT }) {
  const active = plugins.filter((plugin) => plugin.enabled && plugin.control);
  return [
    "// Generated by service/control/scripts/generate-plugins.js; do not edit.",
    `// Control entries of the plugins in ${shown(root, configPath)}.`,
    ...active.map((plugin, index) => `import plugin${index} from ${JSON.stringify(importPath(outFile, plugin.control))};`),
    "",
    "export default [",
    ...active.map((plugin, index) => (
      `  { name: ${JSON.stringify(plugin.name)}, version: ${JSON.stringify(plugin.version)}, options: ${JSON.stringify(plugin.options)}, factory: plugin${index} },`
    )),
    "];",
    "",
  ].join("\n");
}

// Rewrites the file only when its content changes, so `wrangler dev` does not
// rebuild in a loop. Throws if a configured plugin cannot be resolved: a
// deploy should not silently leave a plugin out.
export function generatePluginModule({ root = ROOT, env = process.env, outFile = OUTPUT } = {}) {
  const { path, plugins } = loadPluginConfig({ root, env });
  const broken = plugins.filter((plugin) => plugin.error);
  if (broken.length) {
    throw new Error(`Cannot bundle the plugins in ${path}:\n${broken.map((plugin) => `  ${plugin.source}: ${plugin.error}`).join("\n")}`);
  }
  mkdirSync(dirname(outFile), { recursive: true });
  const source = renderPluginModule({ configPath: path, plugins, outFile, root });
  let current = null;
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    // First run.
  }
  if (current !== source) writeFileSync(outFile, source);
  return { configPath: path, plugins: plugins.filter((plugin) => plugin.enabled && plugin.control).map((plugin) => plugin.name) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    loadEnvFile(process.env.DRIVEIN_ENV_FILE ?? `${ROOT}.env`);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  try {
    const { configPath, plugins } = generatePluginModule();
    console.log(`Control plugins from ${shown(ROOT, configPath)}: ${plugins.length ? plugins.join(", ") : "none"}`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
